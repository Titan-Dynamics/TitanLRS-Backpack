Import("env")
import os
import filecmp
import shutil
import tempfile

def get_version(env):
    return '%s (%s)' % (env.get('GIT_VERSION'), env.get('GIT_SHA'))

def build_webcontent_h(env):
    """Generate include/WebContent.h — a thin wrapper that:
    1. Defines the VERSION constant (injected by the build system).
    2. Selects and includes the pre-built web-asset header for this target.

    The actual asset headers (html/headers/web-*.h) are generated by
    `npm run build:all` in the html/ directory and committed to the repo.
    """
    version = get_version(env)

    content = (
        '// Generated by python/build_html.py — do not edit manually.\n'
        '// Web-asset headers are produced by: cd html && npm run build:all\n'
        '#pragma once\n\n'
        'const char *VERSION = "%s";\n\n'
        '#if defined(TARGET_TX_BACKPACK)\n'
        '  #include "../html/headers/web-txbp.h"\n'
        '#elif defined(TARGET_VRX_BACKPACK) || defined(AAT_BACKPACK)\n'
        '  #include "../html/headers/web-vrx.h"\n'
        '#elif defined(TARGET_TIMER_BACKPACK)\n'
        '  #include "../html/headers/web-timer.h"\n'
        '#else\n'
        '  #error "No web UI header for this target — run: cd html && npm run build:all"\n'
        '#endif\n'
    ) % version

    fd, path = tempfile.mkstemp(suffix='.h')
    try:
        with os.fdopen(fd, 'w') as out:
            out.write(content)
        if not os.path.exists("include/WebContent.h") or not filecmp.cmp(path, "include/WebContent.h"):
            shutil.copyfile(path, "include/WebContent.h")
    finally:
        if os.path.exists(path):
            os.remove(path)

build_webcontent_h(env)
